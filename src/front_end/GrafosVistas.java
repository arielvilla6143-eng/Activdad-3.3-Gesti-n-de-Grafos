    private void btnAgregarVerticeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnAgregarVerticeActionPerformed
        try {
    String id = txtId.getText().trim();
    String nombre = txtNombre.getText().trim();
    String tipo = txtTipo.getText().trim();
    String estado = txtEstado.getText().trim();
    
    if (id.isEmpty() || nombre.isEmpty() || tipo.isEmpty() || estado.isEmpty()) {
        JOptionPane.showMessageDialog(this, "Los campos obligatorios no pueden estar vacíos.", "Campos incompletos", JOptionPane.WARNING_MESSAGE);
        return;
    }
    
    double capacidad = Double.parseDouble(txtCapacidad.getText().trim());
    Vertice v = new Vertice(id, nombre, tipo, estado, capacidad);
    
    if (miGrafo.agregarVertice(v)) {
        JOptionPane.showMessageDialog(this, "Vértice " + id + " agregado exitosamente.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, "El identificador " + id + " ya existe en el grafo.", "Error de Duplicidad", JOptionPane.ERROR_MESSAGE);
    }
} catch (NumberFormatException ex) {
    JOptionPane.showMessageDialog(this, "La capacidad debe ser un valor numérico válido.", "Error de Formato", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnAgregarVerticeActionPerformed

