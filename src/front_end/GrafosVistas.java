    private void btnEliminarAristaActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarAristaActionPerformed
        txtResultados.setText(""); 
String origen = txtOrigen.getText().trim();
String destino = txtDestino.getText().trim();

if (origen.isEmpty() || destino.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingresa Origen y Destino para eliminar la ruta.", "Campos vacíos", JOptionPane.WARNING_MESSAGE);
    return;
}

if (miGrafo.eliminarArista(origen, destino)) {
    JOptionPane.showMessageDialog(this, "Ruta de " + origen + " a " + destino + " eliminada.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
} else {
    JOptionPane.showMessageDialog(this, "La ruta no existe.", "Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnEliminarAristaActionPerformed

