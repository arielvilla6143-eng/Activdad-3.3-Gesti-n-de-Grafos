    private void btnBuscarVerticeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarVerticeActionPerformed
txtResultados.setText(""); 
String id = txtId.getText().trim();

if (id.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingresa un ID para buscar.", "Campo vacío", JOptionPane.WARNING_MESSAGE);
    return;
}

Vertice v = miGrafo.buscarVertice(id);
if (v != null) {
    String mensaje = "ID: " + v.getId() + "\nNombre: " + v.getNombre() + 
                     "\nTipo: " + v.getTipo() + "\nEstado: " + v.getEstado() + 
                     "\nCapacidad: " + v.getCapacidad();
    JOptionPane.showMessageDialog(this, mensaje, "Nodo Encontrado", JOptionPane.INFORMATION_MESSAGE);
} else {
    JOptionPane.showMessageDialog(this, "No existe el vértice " + id, "No encontrado", JOptionPane.WARNING_MESSAGE);
}
    }//GEN-LAST:event_btnBuscarVerticeActionPerformed

    private void btnEliminarVerticeActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEliminarVerticeActionPerformed
        txtResultados.setText(""); 
String id = txtId.getText().trim();

if (id.isEmpty()) {
    JOptionPane.showMessageDialog(this, "Ingresa un ID para eliminar.", "Campo vacío", JOptionPane.WARNING_MESSAGE);
    return;
}

if (miGrafo.eliminarVertice(id)) {
    JOptionPane.showMessageDialog(this, "Vértice " + id + " eliminado.", "Éxito", JOptionPane.INFORMATION_MESSAGE);
} else {
    JOptionPane.showMessageDialog(this, "El vértice " + id + " no existe.", "Error", JOptionPane.ERROR_MESSAGE);
}
    }//GEN-LAST:event_btnEliminarVerticeActionPerformed

